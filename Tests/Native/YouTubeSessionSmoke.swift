import Foundation
import SwiftUI
import WebKit

private enum SmokeFailure: Error, CustomStringConvertible {
    case assertion(String)
    var description: String { switch self { case .assertion(let message): return message } }
}

/// Uses a real WindowServer/AppKit run loop and real WKWebViews. Only the remote
/// IFrame API is replaced by a local fixture; this is not a live-video test.
@main private struct YouTubeSessionSmoke {
    @MainActor static func main() {
        let application = NSApplication.shared
        application.setActivationPolicy(.accessory)
        Task { @MainActor in
            do {
                guard CommandLine.arguments.count == 2 else { throw SmokeFailure.assertion("Pass the fixture JavaScript path.") }
                let fixture = try String(contentsOfFile: CommandLine.arguments[1], encoding: .utf8)
                try await run(fixture: fixture)
                print("PASS: native WKWebView bridge, controls, state validation, SwiftUI handoff, deferred mute intent, failed-session retry, error mapping, and disposal.")
                print("Local IFrame API fixture only; no live YouTube playback was tested.")
                exit(0)
            } catch {
                fputs("FAIL: \(error)\n", stderr)
                exit(1)
            }
        }
        Task { @MainActor in
            try? await Task.sleep(nanoseconds: 120_000_000_000)
            fputs("FAIL: native smoke test exceeded its 120-second deadline.\n", stderr)
            exit(1)
        }
        application.run()
    }

    @MainActor private static func run(fixture: String) async throws {
        try require(Bundle.main.bundleIdentifier == "com.m4d135.FluxIPTV.NativeSmoke",
                    "Run the harness from the .app generated by scripts/test-youtube-session.sh.")
        let trailer = YouTubeTrailer(videoID: "M7lc1UVf-VE")!
        let session = YouTubeTrailerSession(trailer: trailer, iframeAPIFixture: fixture)
        var readyWasDelivered = false
        session.onReady = { readyWasDelivered = true }
        guard let webView = session.fixtureWebView else { throw SmokeFailure.assertion("Session did not create a WKWebView.") }
        let window = NSWindow(contentRect: NSRect(x: 50, y: 50, width: 960, height: 600),
                              styleMask: [.titled], backing: .buffered, defer: false)
        window.isReleasedWhenClosed = false
        let container = NSView(frame: NSRect(x: 0, y: 0, width: 960, height: 600))
        window.contentView = container
        let inline = NSHostingView(rootView: AnyView(YouTubeTrailerSurface(session: session)))
        inline.frame = NSRect(x: 10, y: 10, width: 480, height: 270)
        container.addSubview(inline)
        window.orderFront(nil)
        defer { session.stop(); window.orderOut(nil); window.close() }

        try await eventually("Inline SwiftUI host did not attach the retained web view.") {
            webView.isDescendant(of: inline)
        }
        session.start()
        try await fixtureLoaded(in: webView)
        try require(session.state == .loading, "Loading a document must not claim playback.")
        try await evaluate("window.fixture.ready()", in: webView)
        try await eventually("Ready event did not cross the native bridge and request playback.") {
            try await number("window.fixture.commands.filter(x => x === 'play').length", in: webView) == 1
        }
        try require(session.state == .loading, "Ready / accepted play must not be reported as PLAYING.")
        try require(readyWasDelivered, "The owner did not receive the ready callback for its native fade.")
        let delay = try await number("Math.round(window.fixture.playTimestamp - window.fixture.readyTimestamp)", in: webView)
        try require(delay >= 500, "Autoplay started before the native visibility transition could finish.")
        let firstCommands = try await string("JSON.stringify(window.fixture.commands.slice(0, 3))", in: webView)
        try require(firstCommands == "[\"mute\",\"mute\",\"play\"]", "Muted preview did not mute before requesting playback.")

        try await evaluate("window.fixture.metrics(30, 120); window.fixture.state(1)", in: webView)
        try await eventually("PLAYING or progress did not cross from WebKit.") {
            session.state == .playing && abs(session.progress - 0.25) < 0.001
        }
        session.play(unmute: true)
        try await eventually("Fullscreen unmute did not reach the actual wrapper.") { !session.isMuted }
        try await eventually("Unmute command was not received in JavaScript.") {
            try await number("window.fixture.commands.filter(x => x === 'unmute').length", in: webView) > 0
        }
        session.start(muted: true)
        try await settle()
        try require(session.fixtureWebView === webView, "Repeated start replaced the native player.")
        let constructions = try await number("window.fixture.constructions", in: webView)
        try require(constructions == 1 && !session.isMuted, "Repeated start reloaded or reset the current player.")

        session.setMuted(true)
        try await eventually("Mute did not reach the web player.") {
            try await boolean("window.fixture.player.muted", in: webView)
        }
        session.seek(by: 15)
        try await eventually("Seek progress was not bridged back to Swift.") { abs(session.progress - 0.375) < 0.001 }
        session.seek(by: -1_000)
        try await eventually("Seek before zero was not clamped.") { abs(session.progress) < 0.001 }
        session.seek(by: 1_000)
        try await eventually("Seek past duration was not clamped.") { abs(session.progress - 1) < 0.001 }
        try await evaluate("window.fixture.metrics(30, 120); window.fixture.state(1)", in: webView)
        try await eventually("Fixture did not restore playback progress.") { abs(session.progress - 0.25) < 0.001 }

        session.togglePlayback()
        try await eventually("Pause did not reach the wrapper.") {
            try await number("window.fixture.commands.filter(x => x === 'pause').length", in: webView) > 0
        }
        try require(session.state == .paused, "Toggle did not pause the session.")
        session.togglePlayback()
        try require(session.state == .loading, "Resume must await PLAYING.")
        try await evaluate("window.fixture.state(1)", in: webView)
        try await eventually("Resume did not accept a real PLAYING event.") { session.state == .playing }

        let playsBeforeTurn = try await number("window.fixture.commands.filter(x => x === 'play').length", in: webView)
        let pausesBeforeTurn = try await number("window.fixture.commands.filter(x => x === 'pause').length", in: webView)
        let seeksBeforeTurn = try await number("window.fixture.commands.filter(x => x === 'seek').length", in: webView)
        session.setBackFacing(false)
        try require(session.state == .paused, "The case front did not suspend the retained player.")
        try await eventually("Turning to the front did not pause the actual wrapper.") {
            try await number("window.fixture.commands.filter(x => x === 'pause').length", in: webView) > pausesBeforeTurn
        }
        // A late PLAYING notification must not start hidden playback, nor erase
        // the intention to resume the previously running trailer on the back.
        try await evaluate("window.fixture.state(1)", in: webView)
        try await settle()
        try require(session.state == .paused, "A late PLAYING event resumed a hidden case back.")
        session.setBackFacing(true)
        try await eventually("Returning to the back did not resume the existing player.") {
            try await number("window.fixture.commands.filter(x => x === 'play').length", in: webView) == playsBeforeTurn + 1
        }
        try await evaluate("window.fixture.state(2)", in: webView)
        try await settle()
        try require(session.state == .loading, "A delayed visibility pause cancelled the pending resume.")
        try await evaluate("window.fixture.state(1)", in: webView)
        try await eventually("The retained player did not resume after the turn.") { session.state == .playing }
        try require(session.fixtureWebView === webView && abs(session.progress - 0.25) < 0.001,
                    "A front/back turn replaced the player or reset its position.")
        let seeksAfterTurn = try await number("window.fixture.commands.filter(x => x === 'seek').length", in: webView)
        let constructionsAfterTurn = try await number("window.fixture.constructions", in: webView)
        try require(seeksAfterTurn == seeksBeforeTurn && constructionsAfterTurn == 1,
                    "Resuming after rotation sought to a new position or rebuilt the document.")

        // A user pause is different from a visibility pause and stays paused.
        session.pause()
        try await evaluate("window.fixture.state(2)", in: webView)
        try await settle()
        let playsBeforeManualTurn = try await number("window.fixture.commands.filter(x => x === 'play').length", in: webView)
        session.setBackFacing(false)
        session.setBackFacing(true)
        try await settle()
        let playsAfterManualTurn = try await number("window.fixture.commands.filter(x => x === 'play').length", in: webView)
        try require(session.state == .paused && playsAfterManualTurn == playsBeforeManualTurn,
                    "Turning the case restarted a trailer paused by the user.")
        session.play()
        try await evaluate("window.fixture.state(1)", in: webView)
        try await eventually("Explicit play after a preserved manual pause failed.") { session.state == .playing }

        try await evaluate("window.fixture.metrics(120, 120); window.fixture.state(0)", in: webView)
        try await eventually("The completed trailer did not become ended.") { session.state == .ended }
        let playsBeforeEndedTurn = try await number("window.fixture.commands.filter(x => x === 'play').length", in: webView)
        session.setBackFacing(false)
        session.setBackFacing(true)
        try await evaluate("window.fixture.state(2)", in: webView)
        try await settle()
        let playsAfterEndedTurn = try await number("window.fixture.commands.filter(x => x === 'play').length", in: webView)
        try require(session.state == .ended && session.progress == 1 && playsAfterEndedTurn == playsBeforeEndedTurn,
                    "Turning the case automatically replayed a finished trailer.")
        session.play()
        try await eventually("Explicit replay did not rewind the retained player.") {
            try await number("window.fixture.player.time", in: webView) == 0
        }
        try await evaluate("window.fixture.metrics(30, 120); window.fixture.state(1)", in: webView)
        try await eventually("Explicit replay did not restore the existing session.") {
            session.state == .playing && abs(session.progress - 0.25) < 0.001
        }

        try await evaluate("window.fixture.staleMessage()", in: webView)
        try await eventually("Fixture child frame did not finish loading.") {
            try await boolean("window.fixture.childReady()", in: webView)
        }
        try await evaluate("window.fixture.childMessage()", in: webView)
        try await settle()
        try require(session.state == .playing, "A stale token or child frame changed the native session.")

        let fullscreen = NSHostingView(rootView: AnyView(YouTubeTrailerSurface(session: session)))
        fullscreen.frame = container.bounds
        container.addSubview(fullscreen)
        try await eventually("Fullscreen did not acquire the same native player.") { webView.isDescendant(of: fullscreen) }
        inline.rootView = AnyView(YouTubeTrailerSurface(session: session))
        inline.layoutSubtreeIfNeeded()
        try await settle()
        try require(webView.isDescendant(of: fullscreen), "An inline update stole the player from fullscreen.")
        try require(session.fixtureWebView === webView && session.state == .playing,
                    "Promotion replaced the player or interrupted its state.")
        let promotedConstructions = try await number("window.fixture.constructions", in: webView)
        try require(promotedConstructions == 1 && abs(session.progress - 0.25) < 0.001,
                    "Promotion reloaded the document or lost playback progress.")

        fullscreen.rootView = AnyView(EmptyView())
        try await eventually("Dismissing fullscreen did not restore the surviving inline host.") { webView.isDescendant(of: inline) }
        fullscreen.rootView = AnyView(YouTubeTrailerSurface(session: session))
        try await eventually("Second promotion failed.") { webView.isDescendant(of: fullscreen) }
        inline.rootView = AnyView(EmptyView())
        try await settle()
        try require(webView.isDescendant(of: fullscreen), "Dismantling the old inline host detached the fullscreen player.")

        try await evaluate("window.fixture.blocked()", in: webView)
        try await eventually("Autoplay blocking was not exposed to the native UI.") { session.state == .blocked }
        session.play()
        try await evaluate("window.fixture.state(1)", in: webView)
        try await eventually("A blocked player could not resume on an explicit play request.") { session.state == .playing }
        try await evaluate("window.fixture.scheduleLateMessage()", in: webView)
        session.stop()
        try require(session.state == .idle && session.fixtureWebView == nil, "Stop did not release the session player.")
        try require(webView.superview == nil, "Stop left its native surface attached.")
        try require(webView.navigationDelegate == nil && webView.uiDelegate == nil, "Stop retained native delegates.")
        try await eventually("Stop left its native script bridge installed.") {
            !(try await boolean("Boolean(window.webkit && window.webkit.messageHandlers && window.webkit.messageHandlers.fluxTrailer)", in: webView))
        }
        try await Task.sleep(nanoseconds: 350_000_000)
        try require(session.state == .idle, "A late callback revived the disposed session.")

        fullscreen.rootView = AnyView(EmptyView())
        let pausedReadySession = YouTubeTrailerSession(trailer: trailer, iframeAPIFixture: fixture)
        defer { pausedReadySession.stop() }
        pausedReadySession.onReady = { pausedReadySession.pause() }
        guard let pausedReadyWebView = pausedReadySession.fixtureWebView else { throw SmokeFailure.assertion("Ready/pause session had no player.") }
        inline.rootView = AnyView(YouTubeTrailerSurface(session: pausedReadySession))
        pausedReadySession.start()
        try await fixtureLoaded(in: pausedReadyWebView)
        try await evaluate("window.fixture.ready()", in: pausedReadyWebView)
        try await eventually("Pause during the ready transition did not reach native state.") { pausedReadySession.state == .paused }
        try await Task.sleep(nanoseconds: 650_000_000)
        let pausedReadyPlays = try await number("window.fixture.commands.filter(x => x === 'play').length", in: pausedReadyWebView)
        try require(pausedReadyPlays == 0, "A cancelled ready transition resumed playback.")
        pausedReadySession.stop()

        let explicitReadySession = YouTubeTrailerSession(trailer: trailer, iframeAPIFixture: fixture)
        defer { explicitReadySession.stop() }
        explicitReadySession.onReady = { explicitReadySession.play(unmute: true) }
        guard let explicitReadyWebView = explicitReadySession.fixtureWebView else { throw SmokeFailure.assertion("Ready/play session had no player.") }
        inline.rootView = AnyView(YouTubeTrailerSurface(session: explicitReadySession))
        explicitReadySession.start()
        try await fixtureLoaded(in: explicitReadyWebView)
        try await evaluate("window.fixture.ready()", in: explicitReadyWebView)
        try await eventually("An explicit ready-time play was not sent to WebKit.") {
            try await number("window.fixture.commands.filter(x => x === 'play').length", in: explicitReadyWebView) == 1
        }
        try await Task.sleep(nanoseconds: 650_000_000)
        let explicitReadyPlays = try await number("window.fixture.commands.filter(x => x === 'play').length", in: explicitReadyWebView)
        try require(explicitReadyPlays == 1, "The delayed automatic request duplicated an explicit ready-time play.")
        try require(!explicitReadySession.isMuted, "Explicit ready-time playback did not preserve unmute.")
        explicitReadySession.stop()

        let audibleStartSession = YouTubeTrailerSession(trailer: trailer, iframeAPIFixture: fixture)
        defer { audibleStartSession.stop() }
        var audibleReady = false
        audibleStartSession.onReady = { audibleReady = true }
        guard let audibleStartWebView = audibleStartSession.fixtureWebView else {
            throw SmokeFailure.assertion("Fullscreen startup session had no player.")
        }
        inline.rootView = AnyView(YouTubeTrailerSurface(session: audibleStartSession))
        audibleStartSession.start(muted: false)
        try await fixtureLoaded(in: audibleStartWebView)
        try await evaluate("window.fixture.ready()", in: audibleStartWebView)
        try await eventually("Fullscreen startup did not become ready.") { audibleReady }
        // Reproduce the first poll while the iframe is muted for the fade.
        // A real player can publish this before its delayed play request.
        try await evaluate("window.fixture.metrics(30, 120); window.fixture.state(-1)", in: audibleStartWebView)
        try await eventually("The startup mute sample did not cross the bridge.") {
            abs(audibleStartSession.progress - 0.25) < 0.001
        }
        try require(!audibleStartSession.isMuted, "A ready-time sample discarded the requested fullscreen sound.")
        try await eventually("Fullscreen startup did not send one play request.") {
            try await number("window.fixture.commands.filter(x => x === 'play').length", in: audibleStartWebView) == 1
        }
        let audibleCommands = try await string("JSON.stringify(window.fixture.commands.slice(0, 3))", in: audibleStartWebView)
        try require(audibleCommands == "[\"mute\",\"unmute\",\"play\"]",
                    "Opening the trailer directly in fullscreen started without sound.")
        audibleStartSession.stop()

        var messages: [Int: String] = [:]
        for code in [101, 150, 100, 153] {
            let errorSession = YouTubeTrailerSession(trailer: trailer, iframeAPIFixture: fixture)
            defer { errorSession.stop() }
            guard let errorWebView = errorSession.fixtureWebView else { throw SmokeFailure.assertion("Error session had no WKWebView.") }
            inline.rootView = AnyView(YouTubeTrailerSurface(session: errorSession))
            errorSession.start()
            try await fixtureLoaded(in: errorWebView)
            try await evaluate("window.fixture.ready()", in: errorWebView)
            try await evaluate("window.fixture.error(\(code))", in: errorWebView)
            try await eventually("YouTube error \(code) did not reach native UI.") {
                if case .failed = errorSession.state { return true }; return false
            }
            if case .failed(let message) = errorSession.state {
                try require(!message.isEmpty, "YouTube error \(code) had no actionable explanation.")
                messages[code] = message
            }
            errorSession.stop()
        }
        try require(messages[101] == messages[150], "Equivalent embed restrictions need the same explanation.")
        try require(messages[100] != messages[101], "Unavailable video and embed restriction were conflated.")
        try require(messages[153]?.contains("153") == true && messages[153] != messages[101],
                    "Application identity error 153 lost its distinct diagnosis.")
        try await controllerHandoff(fixture: fixture, inline: inline)
    }

    /// Exercise the real owner across its queued handoff, before any player
    /// exists. This is the same mute-intent boundary used while tvOS awaits a
    /// native URL; the local web fixture makes its result observable offline.
    @MainActor private static func controllerHandoff(fixture: String, inline: NSHostingView<AnyView>) async throws {
        let trailer = YouTubeTrailer(videoID: "M7lc1UVf-VE")!
        guard let context = CGContext(data: nil, width: 1, height: 1, bitsPerComponent: 8,
                                      bytesPerRow: 4, space: CGColorSpaceCreateDeviceRGB(),
                                      bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue),
              let image = context.makeImage() else { throw SmokeFailure.assertion("Cannot create the offline controller thumbnail.") }
        let thumbnailKey = trailer.thumbnailURL.absoluteString as NSString
        ArtworkLoader.cache.setObject(FluxBitmap(image), forKey: thumbnailKey)
        defer { ArtworkLoader.cache.removeObject(forKey: thumbnailKey) }

        let controller = CaseMediaPreviewController()
        controller.iframeAPIFixture = fixture
        defer { controller.stop(); inline.rootView = AnyView(EmptyView()) }
        let item = IPTVItem(id: "controller-trailer", sourceID: UUID(), name: "Local trailer fixture", group: "Fixture",
                            logoURL: nil, kind: .movie, directURL: nil, xtreamStreamID: nil, fileExtension: nil)
        controller.setBackFacing(true)
        controller.update(item: item, details: IPTVDetails(trailerURL: trailer.watchURL), filmURL: nil,
                          backVisible: true, automatic: false, delay: .one)
        controller.setYouTubeViewportEligible(true)
        try require(controller.activateTrailer(), "The controller rejected a valid trailer activation.")
        try require(controller.youtubeSession == nil && controller.player == nil,
                    "The queued handoff no longer permits testing mute before player creation.")
        // Reproduces Return from fullscreen while the trailer is still loading.
        controller.setMuted(true)
        try await eventually("The controller did not create its first web session.") { controller.youtubeSession != nil }
        guard let firstSession = controller.youtubeSession, let firstWebView = firstSession.fixtureWebView else {
            throw SmokeFailure.assertion("The controller's first session has no web view.")
        }
        try require(controller.isMuted && firstSession.isMuted,
                    "The queued activation overwrote a mute requested before player creation.")
        inline.rootView = AnyView(YouTubeTrailerSurface(session: firstSession))
        try await fixtureLoaded(in: firstWebView)
        try await evaluate("window.fixture.ready()", in: firstWebView)
        try await eventually("The controller's first session did not request playback.") {
            try await number("window.fixture.commands.filter(x => x === 'play').length", in: firstWebView) == 1
        }
        let firstPlayerMuted = try await boolean("window.fixture.player.muted", in: firstWebView)
        try require(firstPlayerMuted,
                    "A muted handoff requested audible playback in the actual web player.")
        try await evaluate("window.fixture.error(153)", in: firstWebView)
        try await eventually("The controller did not expose the fixture failure.") { controller.phase == .failed }

        controller.togglePlayback()
        try await eventually("Fullscreen Play could not recreate the failed web session.") {
            guard let current = controller.youtubeSession else { return false }
            return current !== firstSession
        }
        guard let retriedSession = controller.youtubeSession, let retriedWebView = retriedSession.fixtureWebView else {
            throw SmokeFailure.assertion("The retried controller session has no web view.")
        }
        try require(firstSession.fixtureWebView == nil && firstWebView.superview == nil,
                    "Retry kept the failed web player attached or retained.")
        try require(controller.isMuted && retriedSession.isMuted,
                    "Retry discarded the user's mute choice.")
        inline.rootView = AnyView(YouTubeTrailerSurface(session: retriedSession))
        try await fixtureLoaded(in: retriedWebView)
        try await evaluate("window.fixture.ready()", in: retriedWebView)
        try await eventually("The new controller session did not request playback.") {
            try await number("window.fixture.commands.filter(x => x === 'play').length", in: retriedWebView) == 1
        }
        try await evaluate("window.fixture.state(1)", in: retriedWebView)
        try await eventually("The new controller session never recovered playback.") { controller.phase == .playing }
        try require(controller.youtubeSession === retriedSession && controller.failureMessage == nil,
                    "Retry duplicated the player or retained the old failure.")
    }

    @MainActor private static func fixtureLoaded(in view: WKWebView) async throws {
        try await eventually("The local IFrame API fixture did not load in WKWebView.") {
            try await number("window.fixture ? window.fixture.constructions : 0", in: view) == 1
        }
    }

    @MainActor private static func evaluate(_ source: String, in view: WKWebView) async throws {
        _ = try await view.evaluateJavaScript(source)
    }

    @MainActor private static func number(_ source: String, in view: WKWebView) async throws -> Int {
        let result = try await view.evaluateJavaScript(source)
        return (result as? NSNumber)?.intValue ?? -1
    }

    @MainActor private static func boolean(_ source: String, in view: WKWebView) async throws -> Bool {
        let result = try await view.evaluateJavaScript(source)
        return (result as? NSNumber)?.boolValue ?? false
    }

    @MainActor private static func string(_ source: String, in view: WKWebView) async throws -> String {
        let result = try await view.evaluateJavaScript(source)
        return result as? String ?? ""
    }

    @MainActor private static func eventually(_ message: String,
                                              condition: @MainActor () async throws -> Bool) async throws {
        let deadline = Date().addingTimeInterval(10)
        var lastError: Error?
        repeat {
            do { if try await condition() { return } } catch { lastError = error }
            try await Task.sleep(nanoseconds: 40_000_000)
        } while Date() < deadline
        throw SmokeFailure.assertion(message + (lastError.map { " Last WebKit error: \($0)" } ?? ""))
    }

    @MainActor private static func settle() async throws { try await Task.sleep(nanoseconds: 120_000_000) }

    @MainActor private static func require(_ condition: @autoclosure () -> Bool, _ message: String) throws {
        if !condition() { throw SmokeFailure.assertion(message) }
    }
}
